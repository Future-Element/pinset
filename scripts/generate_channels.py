#!/usr/bin/env python3
"""Generate distribution manifests from the stable version in release.json.

Run from the repository root: python scripts/generate_channels.py --verify-archives
Generated candidates go below --output-root (default: output/channels). Review
them before updating the checked-in packaging samples or external registries.
This script does not commit, push, submit changes, publish, or install packages.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path


REPOSITORY = "Future-Element/pinset"
REPO_URL = f"https://github.com/{REPOSITORY}"
HOMEPAGE = "https://pinset.future-element.com"
TARGETS = ("linux-x86_64", "linux-aarch64", "macos-aarch64", "windows-x86_64")
MANIFEST_VERSION = "1.12.0"
PACKAGE_ID = "FutureElement.Pinset"
MAX_METADATA_BYTES = 2 * 1024 * 1024
MAX_ARCHIVE_BYTES = 64 * 1024 * 1024


def download(url: str, limit: int) -> bytes:
    if not url.startswith("https://"):
        raise ValueError("only HTTPS release resources are accepted")
    request = urllib.request.Request(url, headers={"User-Agent": "pinset-channel-generator"})
    with urllib.request.urlopen(request, timeout=60) as response:
        if not response.geturl().startswith("https://"):
            raise ValueError("release resource redirected away from HTTPS")
        data = response.read(limit + 1)
    if len(data) > limit:
        raise ValueError(f"release resource exceeds {limit} bytes: {url}")
    return data


def parse_checksums(text: str) -> dict[str, str]:
    checksums: dict[str, str] = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line:
            continue
        match = re.fullmatch(r"([0-9A-Fa-f]{64}) [ *]([^/\\\r\n]+)", line)
        if not match:
            raise ValueError(f"invalid SHA256SUMS line {number}")
        value, name = match.groups()
        if name in checksums:
            raise ValueError(f"duplicate SHA256SUMS entry: {name}")
        checksums[name] = value.lower()
    return checksums


def write(root: Path, name: str, value: str) -> None:
    destination = root / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(value.rstrip() + "\n", encoding="utf-8", newline="\n")


def homebrew(version: str, urls: dict[str, str], hashes: dict[str, str]) -> str:
    return f'''# Generated by scripts/generate_channels.py; update the release input, not these hashes.
class Pinset < Formula
  desc "Lock project toolchains and explain their execution paths"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  on_macos do
    depends_on arch: :arm64
    url "{urls['macos-aarch64']}"
    sha256 "{hashes['macos-aarch64']}"
  end

  on_linux do
    on_intel do
      url "{urls['linux-x86_64']}"
      sha256 "{hashes['linux-x86_64']}"
    end
    on_arm do
      url "{urls['linux-aarch64']}"
      sha256 "{hashes['linux-aarch64']}"
    end
  end

  def install
    # Keep the real CLI and its router beside each other in the same keg.
    bin.install "pinset", "pinset-shim"
  end

  def caveats
    <<~EOS
      Register or refresh managed tool entries using this Homebrew installation:
        #{{opt_bin}}/pinset self repair
      Then follow the PATH fragment printed by:
        #{{opt_bin}}/pinset self shell
      Repeat self repair with the absolute path above after brew upgrade pinset.
      Upgrade this installation with Homebrew; pinset self update changes managed files.
      Homebrew uninstall removes this keg. PINSET_HOME keeps copied CLI/router,
      tool entries, SDKs and state, so pinset may remain on PATH.
    EOS
  end

  test do
    ENV["PINSET_HOME"] = testpath/"home"
    assert_match "pinset {version}", shell_output("#{{bin}}/pinset --version")
    assert_path_exists bin/"pinset-shim"
    system bin/"pinset", "self", "repair"
    assert_path_exists testpath/"home/v3/bin/pinset-shim"
  end
end
'''


def scoop(version: str, urls: dict[str, str], hashes: dict[str, str]) -> str:
    manifest = {
        "version": version,
        "description": "Lock project toolchains and explain their execution paths",
        "homepage": HOMEPAGE,
        "license": "MIT",
        "architecture": {"64bit": {"url": urls["windows-x86_64"], "hash": hashes["windows-x86_64"]}},
        "pre_install": [
            "if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64' -or $env:PROCESSOR_ARCHITEW6432 -eq 'ARM64') { throw 'Pinset publishes native Windows x64 only; Windows ARM64 is not supported.' }"
        ],
        "bin": "pinset.exe",
        "post_install": [
            "& \"$dir\\pinset.exe\" self repair",
            "if ($LASTEXITCODE -ne 0) { throw 'Pinset could not refresh managed tool entries. Run this installation with self repair after resolving the reported error.' }",
        ],
        "notes": [
            "The CLI and pinset-shim.exe are installed together. Tool entries live in PINSET_HOME\\v3\\bin.",
            "Run pinset self shell powershell to print the explicit shell setup; no profile is edited.",
            "Use scoop update pinset for upgrades; do not use pinset self update for this Scoop installation.",
            "Uninstalling deletes Scoop's package files. PINSET_HOME keeps copied CLI/router, tool entries, SDKs and state, so pinset may remain on PATH.",
        ],
        # Use the repository URL and the official helper's default capture group.
        # Older Scoop versions append /releases/latest even to an API URL.
        "checkver": {"github": REPO_URL},
        "autoupdate": {
            "architecture": {
                "64bit": {"url": f"{REPO_URL}/releases/download/v$version/pinset-v$version-windows-x86_64.zip"}
            },
            "hash": {"url": "$baseurl/SHA256SUMS"},
        },
    }
    return json.dumps(manifest, indent=4, ensure_ascii=False)


def winget(version: str, urls: dict[str, str], hashes: dict[str, str]) -> dict[str, str]:
    version_file = f'''# yaml-language-server: $schema=https://aka.ms/winget-manifest.version.{MANIFEST_VERSION}.schema.json
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: {MANIFEST_VERSION}
'''
    locale_file = f'''# yaml-language-server: $schema=https://aka.ms/winget-manifest.defaultLocale.{MANIFEST_VERSION}.schema.json
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
PackageLocale: en-US
Publisher: Future Element
PublisherUrl: https://github.com/Future-Element
PublisherSupportUrl: {REPO_URL}/issues
Author: Future Element
PackageName: Pinset
PackageUrl: {HOMEPAGE}
License: MIT
LicenseUrl: {REPO_URL}/blob/v{version}/LICENSE
ShortDescription: Lock project toolchains and explain their execution paths
Moniker: pinset
Tags:
  - cli
  - developer-tools
  - toolchain
  - version-manager
ReleaseNotesUrl: {REPO_URL}/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: {MANIFEST_VERSION}
'''
    installer_file = f'''# yaml-language-server: $schema=https://aka.ms/winget-manifest.installer.{MANIFEST_VERSION}.schema.json
PackageIdentifier: {PACKAGE_ID}
PackageVersion: {version}
InstallerType: zip
NestedInstallerType: portable
UpgradeBehavior: install
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Microsoft.VCRedist.2015+.x64
Commands:
  - pinset
# The archive is kept in one package directory; aliases point to these original names.
NestedInstallerFiles:
  - RelativeFilePath: pinset.exe
    PortableCommandAlias: pinset
  - RelativeFilePath: pinset-shim.exe
    PortableCommandAlias: pinset-shim
UnsupportedOSArchitectures:
  - x86
  - arm
  - arm64
Installers:
  - Architecture: x64
    InstallerUrl: {urls['windows-x86_64']}
    InstallerSha256: {hashes['windows-x86_64'].upper()}
ManifestType: installer
ManifestVersion: {MANIFEST_VERSION}
'''
    return {
        f"{PACKAGE_ID}.yaml": version_file,
        f"{PACKAGE_ID}.locale.en-US.yaml": locale_file,
        f"{PACKAGE_ID}.installer.yaml": installer_file,
    }


def aqua() -> str:
    # This is a reviewable local registry candidate, not a claim of upstream acceptance.
    return '''# yaml-language-server: $schema=https://raw.githubusercontent.com/aquaproj/aqua/main/json-schema/registry.json
packages:
  - type: github_release
    repo_owner: Future-Element
    repo_name: pinset
    description: Lock project toolchains and explain their execution paths
    asset: pinset-{{.Version}}-{{.OS}}-{{.Arch}}.zip
    format: zip
    version_constraint: semver(">= 3.0.9, < 4.0.0")
    supported_envs:
      - linux/amd64
      - linux/arm64
      - darwin/arm64
      - windows/amd64
    rosetta2: false
    windows_arm_emulation: false
    replacements:
      darwin: macos
      amd64: x86_64
      arm64: aarch64
    files:
      - name: pinset
        src: pinset
      - name: pinset-shim
        src: pinset-shim
    overrides:
      - goos: windows
        files:
          - name: pinset
            src: pinset.exe
          - name: pinset-shim
            src: pinset-shim.exe
    checksum:
      type: github_release
      asset: SHA256SUMS
      algorithm: sha256
    github_artifact_attestations:
      signer_workflow: Future-Element/pinset/.github/workflows/release.yml
'''


def generate(args: argparse.Namespace) -> dict:
    release_input = args.release_json.read_bytes()
    version = json.loads(release_input)["published"]
    if not isinstance(version, str) or not re.fullmatch(r"3\.\d+\.\d+", version):
        raise ValueError("release.json published must be an exact stable Pinset 3 version")
    if tuple(map(int, version.split("."))) < (3, 0, 9):
        raise ValueError("these channel templates support Pinset 3.0.9 and later")
    tag = f"v{version}"
    release_url = f"{REPO_URL}/releases/download/{tag}"
    metadata_url = f"https://api.github.com/repos/{REPOSITORY}/releases/tags/{tag}"
    metadata_bytes = args.release_metadata.read_bytes() if args.release_metadata else download(metadata_url, MAX_METADATA_BYTES)
    metadata = json.loads(metadata_bytes)
    if metadata.get("tag_name") != tag or metadata.get("draft") is not False or metadata.get("prerelease") is not False:
        raise ValueError("channel manifests require the exact published stable release")
    assets = {asset["name"]: asset for asset in metadata.get("assets", [])}
    checksum_asset = assets.get("SHA256SUMS", {})
    checksum_url = f"{release_url}/SHA256SUMS"
    if checksum_asset.get("browser_download_url") != checksum_url:
        raise ValueError("published SHA256SUMS asset is missing or has an unexpected URL")
    checksum_bytes = args.checksums.read_bytes() if args.checksums else download(checksum_url, MAX_METADATA_BYTES)
    checksum_digest = hashlib.sha256(checksum_bytes).hexdigest()
    if checksum_asset.get("digest") != f"sha256:{checksum_digest}":
        raise ValueError("SHA256SUMS does not match GitHub's published asset digest")
    checksums = parse_checksums(checksum_bytes.decode("utf-8"))
    urls: dict[str, str] = {}
    hashes: dict[str, str] = {}
    evidence = []
    for target in TARGETS:
        name = f"pinset-{tag}-{target}.zip"
        asset = assets.get(name, {})
        url = f"{release_url}/{name}"
        sha = checksums.get(name)
        if not sha or asset.get("browser_download_url") != url or asset.get("digest") != f"sha256:{sha}":
            raise ValueError(f"published archive metadata and SHA256SUMS disagree: {name}")
        urls[target] = url
        hashes[target] = sha
        item = {"target": target, "url": url, "sha256": sha, "archive_rehashed": False}
        if args.verify_archives:
            data = download(url, MAX_ARCHIVE_BYTES)
            if hashlib.sha256(data).hexdigest() != sha:
                raise ValueError(f"downloaded archive digest mismatch: {name}")
            expected = ["pinset.exe", "pinset-shim.exe"] if target.startswith("windows-") else ["pinset", "pinset-shim"]
            with zipfile.ZipFile(io.BytesIO(data)) as archive:
                if sorted(archive.namelist()) != sorted(expected) or any(archive.getinfo(entry).file_size == 0 for entry in expected):
                    raise ValueError(f"archive must contain exactly the adjacent CLI/router pair: {name}")
            item.update(archive_rehashed=True, archive_entries=expected)
        evidence.append(item)

    # Generate everything before writing, so a failed metadata/archive validation leaves no partial manifests.
    files = {
        "packaging/homebrew/pinset.rb": homebrew(version, urls, hashes),
        "packaging/scoop/pinset.json": scoop(version, urls, hashes),
        "packaging/aqua/registry.yaml": aqua(),
        "packaging/aqua/pkg.yaml": f"packages:\n  - name: Future-Element/pinset@{tag}\n",
    }
    base = f"packaging/winget/manifests/f/FutureElement/Pinset/{version}"
    files.update({f"{base}/{name}": content for name, content in winget(version, urls, hashes).items()})
    for name, content in files.items():
        write(args.output_root, name, content)
    write(args.output_root, "evidence/release.json", release_input.decode("utf-8"))
    write(args.output_root, "evidence/release-metadata.json", json.dumps(metadata, indent=2, ensure_ascii=False))
    write(args.output_root, "evidence/SHA256SUMS", checksum_bytes.decode("utf-8"))
    report = {
        "version": version,
        "release_url": metadata["html_url"],
        "release_json_sha256": hashlib.sha256(release_input).hexdigest(),
        "checksums_sha256": checksum_digest,
        "assets": evidence,
        "files": sorted(files),
        "publication": {"homebrew_tap": "not published by this script", "scoop_bucket": "not published by this script", "winget": "not submitted by this script", "aqua": "not submitted by this script"},
    }
    write(args.output_root, "evidence/generation.json", json.dumps(report, indent=2))
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-json", type=Path, default=Path("release.json"))
    parser.add_argument("--checksums", type=Path, help="local SHA256SUMS; still checked against published metadata")
    parser.add_argument("--release-metadata", type=Path, help="local GitHub release JSON for reproducible offline generation")
    parser.add_argument("--output-root", type=Path, default=Path("output/channels"))
    parser.add_argument("--verify-archives", action="store_true", help="download all four ZIPs, rehash them and verify adjacent binary entries")
    args = parser.parse_args()
    try:
        report = generate(args)
    except (OSError, ValueError, KeyError, TypeError, zipfile.BadZipFile) as error:
        print(f"channel generation failed: {error}", file=sys.stderr)
        return 1
    print(json.dumps({"version": report["version"], "output_root": str(args.output_root.resolve()), "files": report["files"], "archives_verified": all(item["archive_rehashed"] for item in report["assets"])}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
